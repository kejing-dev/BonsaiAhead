"""Copies the Tripo LOD props (design assetFiles, gate B defaults: pot B celadon, stand B light oak, tray B slate + sand,
stone A scholar rock, can A copper) into app/src/main/assets/models/ and writes domain/ModelCalib.kt (GENERATED, never
edit by hand): per model the raw bounds and the calibration (profile D25: bottom centre to the origin, long side along X,
fitted to the design size in design units, non-uniform scale <= 15 %), plus the spout side of the can.

  ~/.factory-venv/bin/python tools/calibrate_models.py

Raw GLBs: ~/Downloads/bonsai-tripo/<id>.glb (Tripo, kj-mbp-m5, 2026-11-17 design station); LOD by the factory's
bin/glb_decimate.py into ~/Downloads/bonsai-tripo/lod/ (pot / tray 6000, stand / can 4000, stone 3000 triangles, 1K).
Light materials (sand, celadon glaze) get an emissive floor = base texture x 0.25 (design assets.lightObjects: white
PBR reads near black in the Shared Space volume).
"""
import json, os, shutil, struct
import numpy as np
import trimesh

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.expanduser("~/Downloads/bonsai-tripo/lod")
OUT = os.path.join(ROOT, "app", "src", "main", "assets", "models")
KT = os.path.join(ROOT, "app", "src", "main", "java", "io", "embodit", "bonsai", "domain", "ModelCalib.kt")

# id: (file, design size x, y, z in design units (actual = x 1.25), emissive floor or None)
MODELS = {
    "tray": ("tray-B.glb", (0.78, 0.03, 0.40), 0.25),
    "stand": ("stand-B.glb", (0.26, 0.10, 0.18), None),
    "pot": ("pot-B.glb", (0.28, 0.07, 0.20), 0.25),
    "stone": ("stone-A.glb", (0.07, 0.06, 0.05), None),
    "can": ("can-A.glb", (0.09, 0.09, 0.06), None),
}


def rewrite(path, name, emissive=None):
    b = bytearray(open(path, "rb").read())
    n = struct.unpack("<I", b[12:16])[0]
    j = json.loads(b[20:20 + n])
    for nd in j["nodes"]:
        nd["name"] = name
    for m in j.get("materials", []):
        m["alphaMode"] = "OPAQUE"  # profile 2026-10-29: props stay opaque
        m.pop("alphaCutoff", None)
        if emissive is not None:
            tex = m.get("pbrMetallicRoughness", {}).get("baseColorTexture")
            if tex:
                m["emissiveTexture"] = {"index": tex["index"]}
                m["emissiveFactor"] = [emissive] * 3
    js = json.dumps(j, separators=(",", ":")).encode()
    while len(js) % 4:
        js += b" "
    rest = b[20 + n:]
    total = 12 + 8 + len(js) + len(rest)
    open(path, "wb").write(struct.pack("<III", 0x46546C67, 2, total) + struct.pack("<II", len(js), 0x4E4F534A) + js + rest)


def main():
    os.makedirs(OUT, exist_ok=True)
    out = ["// GENERATED by tools/calibrate_models.py (design entities3d sizes + D25 calibration). Do not edit by hand.",
           "package io.embodit.bonsai.domain", "",
           "/**",
           " * One Tripo prop: raw GLB bounds, the per-axis scale to the design size (design units, the content root scales x 1.25)",
           " * and the raw point that lands on the origin (bottom centre). [yaw] turns the raw model before scaling (radians).",
           " */",
           "data class ModelCal(val id: String, val file: String, val rawMin: V3, val rawMax: V3, val scale: V3, val pivot: V3, val yaw: Float, val triangles: Int) {",
           "    /** Calibrated size, design units (x, y, z). */",
           "    val size: V3 get() = V3((rawMax.x - rawMin.x) * scale.x, (rawMax.y - rawMin.y) * scale.y, (rawMax.z - rawMin.z) * scale.z)",
           "}", "", "object ModelCalib {"]

    def v3(a):
        return "V3(%.5ff, %.5ff, %.5ff)" % tuple(a)

    for mid, (f, size, em) in MODELS.items():
        dst = os.path.join(OUT, mid + ".glb")
        shutil.copyfile(os.path.join(SRC, f), dst)
        rewrite(dst, mid, em)
        sc = trimesh.load(dst)
        g = list(sc.geometry.values())[0]
        lo, hi = sc.bounds
        ext = hi - lo
        yaw = 0.0
        if mid == "can":
            # the spout is the thin end: compare how many vertices sit in each outer quarter along X
            x = g.vertices[:, 0]
            q = (hi[0] - lo[0]) * 0.25
            left = (x < lo[0] + q).sum()
            right = (x > hi[0] - q).sum()
            # design: the spout points at the pot (-X); the thinner end has fewer vertices
            spout_right = right < left
            yaw = float(np.pi) if spout_right else 0.0
            print("can spout on raw %s (left %d / right %d vertices) -> yaw %.2f" % ("+X" if spout_right else "-X", left, right, yaw))
        k = np.array(size) / ext
        # footprint first (x, z), height follows; non-uniform part limited to 15 % (design assetFiles.calibration)
        uni = float(np.exp((np.log(k[0]) + np.log(k[2])) / 2))
        k = np.clip(k, uni * 0.85, uni * 1.15)
        # heights stack the soil at design y 0.20 (tray 0.03 + stand 0.10 + pot 0.07): the height is forced to the design value
        if mid in ("tray", "stand", "pot"):
            k[1] = size[1] / ext[1]
        cx, cz = (lo[0] + hi[0]) / 2, (lo[2] + hi[2]) / 2
        out.append('    /** %s: Tripo %s, %d triangles, fitted to %s design units (non-uniform <= 15 %%). */' % (mid, f, len(g.faces), size))
        out.append('    val %s = ModelCal("%s", "%s", %s, %s, %s, %s, %.5ff, %d)' % (mid.upper(), mid, f, v3(lo), v3(hi), v3(k), v3((cx, lo[1], cz)), yaw, len(g.faces)))
        print("%-6s ext %s -> scale %s size %s tris %d" % (mid, ext.round(3), k.round(4), (ext * k).round(4), len(g.faces)))
    out.append("    val ALL = listOf(TRAY, STAND, POT, STONE, CAN)")
    out.append("}")
    open(KT, "w").write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
